from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
    messages : Annotated[list,add] = Field(..., description="List of messages to be processed by the agent.")
    user_questions : str = Field(..., description="The Original question asked my user")
    curated_ques : str = Field(..., description="The curated question generated by the agent.")
    prompt_query_context : str = Field(..., description="A detailed prompt with SQL DB context to be used for generating the query.")
    generated_sql_query : str = Field(..., description="The SQL query generated by the agent.")
    is_safe : Literal["Yes", "No"] = Field(..., description="Indicates whether the query is safe to execute.")
    comments : str = Field(..., description="Comments or reasoning provided by the agent regarding the safety of the SQL query.")
    sql_query_execution_result : str = Field(..., description="The result of executing the SQL query.")
    final_answer : str = Field(..., description="The final answer generated by the agent based on the SQL query execution result.")
    

class JudgeSchema(BaseModel):
    answer : Literal["Yes", "No"] = Field(..., description="Indicates whether the sql query is safe to execute or not.")
    comments : str = Field(..., description="Comments or reasoning provided by the agent regarding the safety of the SQL query.")

class ETLAgentSchema(BaseModel):
    messages: Annotated[list,add] = Field(..., description="List of messages to be proccessed by the ETL agent")

class RouterSchema(BaseModel):
    answer : Literal["sql","etl"] = Field(..., description="Indicates whether the user's question is related to SQL or ETL Operations.")
    comments : str = Field(..., description="Additonal Comments or feedback regarding the classicfication of the user's question.")

class DataAgentSchema(BaseModel):
    messages : Annotated[list,add] = Field(..., description="List of messages to be processed by the Data agent")
    route_response : str = Field(..., description="The response from the router indicating whether to route to SQL or ETL operations")
